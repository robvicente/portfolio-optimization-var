"""## 1.2. Portfolio Optimization ##"""

def portfolio_metrics(weights, mean_returns, cov_matrix, risk_free_rate=0.01):
    # Calculation of expected return and risk
    portfolio_return = np.sum(mean_returns * weights) * 252
    portfolio_stddev = np.sqrt(np.dot(weights.T, np.dot(cov_matrix, weights))) * np.sqrt(252)
    sharpe_ratio = (portfolio_return - risk_free_rate) / portfolio_stddev
    return portfolio_return, portfolio_stddev, sharpe_ratio

def neg_sharpe_ratio(weights, mean_returns, cov_matrix, risk_free_rate=0.01):
    # We minimize the negative Sharpe ratio
    return -portfolio_metrics(weights, mean_returns, cov_matrix, risk_free_rate)[2]

def get_optimal_portfolio(mean_returns, cov_matrix, num_assets, sector_limits):
    # Constraints: no short selling and no more than 25% in a sector
    bounds = tuple((0, sector_limits) for _ in range(num_assets))
    constraints = {'type': 'eq', 'fun': lambda x: np.sum(x) - 1}
    result = minimize(neg_sharpe_ratio, num_assets*[1./num_assets], args=(mean_returns, cov_matrix),
                      method='SLSQP', bounds=bounds, constraints=constraints)
    return result.x

