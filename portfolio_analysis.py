import numpy as np
import pandas as pd
import yfinance as yf
import matplotlib.pyplot as plt

# 1. Download historical data
tickers = ['AAPL', 'AMZN', 'WMT', 'JPM', 'GS', 'MSFT','JCI','KO','AZN','PG','XOM','HAS','CVX']
start_date = '2019-09-25'
end_date = '2023-09-25'
data = yf.download(tickers, start=start_date, end=end_date)['Close']
returns = np.log(data / data.shift(1)).dropna()
returns

# 2. Portfolio parameters
portfolio_value = 1_000_000
weights = np.array([0.067, 0.073, 0.069, 0.063, 0.07, 0.075, 0.075, 0.08, 0.089, 0.079, 0.085, 0.08, 0.095 ])  # Portfolio weights

# Portfolio returns calculation
portfolio_returns = returns.dot(weights)

# Portfolio Parametric VaR
confidence_level = 0.95
z_score = np.percentile(portfolio_returns, (1 - confidence_level) * 100)

def var_parametric(returns, weights, portfolio_value, confidence_level=0.95):
    mean = np.mean(returns.dot(weights))
    std_dev = np.std(returns.dot(weights))
    z = np.percentile(returns, (1 - confidence_level) * 100)
    var = portfolio_value * (mean - z * std_dev)
    return var

# 3. Component and Incremental VaR
cov_matrix = returns.cov()  # Covariance matrix of the assets
portfolio_std = np.sqrt(weights.T @ cov_matrix @ weights)  # Portfolio standard deviation
var_total = var_parametric(returns, weights, portfolio_value)

# Component VaR: Contribution of each asset to the total VaR
var_component = weights * (cov_matrix @ weights) / portfolio_std
var_component_total = var_component * portfolio_value

# Incremental VaR: Change in VaR if each asset is removed
var_incremental = var_total - (weights * var_component_total)

# 4. Component VaR chart
components = pd.DataFrame({
    'Component VaR ($)': var_component_total,
    'Incremental VaR ($)': var_incremental
}, index=tickers)

components.plot(kind='bar', figsize=(10, 7), title="Portfolio Risk Composition (Component and Incremental VaR)")
plt.show()

# 5. Backtesting
# For backtesting, we compare the number of days where the actual loss exceeds the estimated VaR.

backtest_violations = (portfolio_returns < -var_total / portfolio_value).sum()
print(f"VaR Violations (Backtesting): {backtest_violations}")

# Backtesting chart
plt.figure(figsize=(10, 6))
plt.plot(portfolio_returns.index, portfolio_returns, label='Portfolio Returns')
plt.axhline(-var_total / portfolio_value, color='red', linestyle='--', label=f'VaR ({confidence_level*100:.0f}% Confidence)')
plt.fill_between(portfolio_returns.index, -var_total / portfolio_value, portfolio_returns.min(), color='red', alpha=0.3, label='VaR Violations')
plt.legend(loc='upper right')
plt.title('VaR Backtesting: Portfolio Returns vs. VaR')
plt.show()

# 6. Stress Testing
# For stress testing, we can analyze scenarios where the market drops 10%, 20%, 30%, etc.

stress_levels = [0.1, 0.2, 0.3]  # Example stress levels
stress_var = {f'Stress {int(level * 100)}%': portfolio_value * level * portfolio_std for level in stress_levels}

# Stress Testing chart
plt.figure(figsize=(10, 6))
stress_values = list(stress_var.values())
plt.bar(stress_var.keys(), stress_values, color='orange')
plt.title('Stress Testing: VaR Impact under Different Stress Levels')
plt.ylabel('VaR ($)')
plt.show()

